#!/usr/bin/env python3
"""Dataset quality report (EDA): class balance, CWE/language mix, size, duplicates, leakage.

  python scripts/dataset_stats.py            # writes docs/DATASET.md
"""
from __future__ import annotations

import csv
import hashlib
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATASET = ROOT / "dataset"


def rows() -> list[dict]:
    out = []
    for name in ("labels.csv", "labels_cpp.csv"):
        p = DATASET / name
        if p.exists():
            with p.open(encoding="utf-8") as fh:
                out += list(csv.DictReader(fh))
    return out


def files_of(r: dict) -> list[Path]:
    p = DATASET / r["path"]
    return sorted(x for x in p.rglob("*") if x.is_file()) if p.is_dir() else [p]


def loc(path: Path) -> int:
    code = 0
    in_block = False
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        s = line.strip()
        if in_block:
            in_block = "*/" not in s
            continue
        if not s or s.startswith(("//", "#", "*")) and not s.startswith(("#include", "#define", "#if", "#endif")):
            continue
        if s.startswith("/*"):
            in_block = "*/" not in s
            continue
        code += 1
    return code


def normalized_hash(path: Path) -> str:
    """Hash with class names / comments / whitespace removed, to catch near-duplicates."""
    t = path.read_text(encoding="utf-8", errors="replace")
    t = re.sub(r"/\*.*?\*/|//[^\n]*|#[^\n]*", "", t, flags=re.S)
    t = re.sub(r"\bCWE\w+", "ID", t)
    t = re.sub(r"\s+", "", t)
    return hashlib.sha256(t.encode()).hexdigest()


def main() -> None:
    data = rows()
    md = ["# Dataset report", "",
          "Generated by `scripts/dataset_stats.py` from `dataset/labels*.csv` and the files they point to.", ""]
    md += ["## Class balance per split", "", "| Split | Kind | bad | good | Total |", "|---|---|---|---|---|"]
    bal = Counter((r["split"], r["kind"], r["label"]) for r in data)
    for split, kind in sorted({(r["split"], r["kind"]) for r in data}):
        b, g = bal[(split, kind, "bad")], bal[(split, kind, "good")]
        md.append(f"| {split} | {kind} | {b} | {g} | {b + g} |")
    md += ["", "## CWE × language (cases)", "", "| Split | CWE family | java | python | c | Total |", "|---|---|---|---|---|---|"]
    mix = Counter((r["split"], r["cwe"], r["lang"]) for r in data)
    for split, cwe in sorted({(r["split"], r["cwe"]) for r in data}):
        cells = [mix[(split, cwe, lang)] for lang in ("java", "python", "c")]
        md.append(f"| {split} | {cwe} | " + " | ".join(map(str, cells)) + f" | {sum(cells)} |")
    md += ["", "## Size (non-blank, non-comment lines per case)", "",
           "| Split | Label | n | min | median | max |", "|---|---|---|---|---|---|"]
    sizes = defaultdict(list)
    for r in data:
        sizes[(r["split"], r["label"])].append(sum(loc(f) for f in files_of(r)))
    for key in sorted(sizes):
        v = sorted(sizes[key])
        md.append(f"| {key[0]} | {key[1]} | {len(v)} | {v[0]} | {v[len(v) // 2]} | {v[-1]} |")
    exact, norm = defaultdict(list), defaultdict(list)
    for r in data:
        for f in files_of(r):
            exact[hashlib.sha256(f.read_bytes()).hexdigest()].append((r["split"], r["case_id"]))
            norm[normalized_hash(f)].append((r["split"], r["case_id"]))
    dup_exact = [v for v in exact.values() if len(v) > 1]
    dup_norm = [v for v in norm.values() if len(v) > 1]
    leak = [v for v in norm.values() if len({s for s, _ in v}) > 1]
    md += ["", "## Duplicates and train/test leakage", "",
           f"- Exact duplicate files: **{len(dup_exact)}**",
           f"- Near-duplicates (comments, identifiers `CWE*`, whitespace removed): **{len(dup_norm)}**"
           + (" — " + "; ".join(", ".join(c for _, c in v) for v in dup_norm) if dup_norm else ""),
           f"- Near-duplicates spanning two splits (leakage): **{len(leak)}**", "",
           "Juliet's bad/good halves of the same test case share sources and sinks by design. "
           "They are kept in the **same** split (`pair` column), so a split never contains one half "
           "of a pair whose other half is in another split.", ""]
    pairs = defaultdict(set)
    for r in data:
        pairs[r["pair"]].add(r["split"])
    split_pairs = [p for p, s in pairs.items() if len(s) > 1]
    md.append(f"- Pairs split across splits: **{len(split_pairs)}**")
    md += ["", "## Provenance", "",
           "| Split | Origin |", "|---|---|"]
    for split, origin in sorted({(r["split"], r["origin"].split(":")[0]) for r in data}):
        md.append(f"| {split} | {origin} |")
    out = ROOT / "docs" / "DATASET.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
